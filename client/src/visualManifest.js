const fallbackCategory = "accessories";

function stableIndex(value, length) {
  const text = String(value ?? "");
  const sum = [...text].reduce((total, char) => total + char.charCodeAt(0), 0);
  return sum % length;
}

function normalizePhotoUrl(url, apiUrl) {
  if (!url || typeof url !== "string") return "";
  if (url.startsWith("/uploads/")) return "";
  if (url.startsWith("http://") || url.startsWith("https://")) return url;
  if (url.startsWith("/") && apiUrl) return `${apiUrl}${url}`;
  return "";
}

export function getCategoryVisual(category, seed = "") {
  const key = CATEGORY_VISUALS[category] ? category : fallbackCategory;
  const visual = CATEGORY_VISUALS[key];
  return {
    ...visual.images[stableIndex(seed || key, visual.images.length)],
    category: key,
    color: visual.color,
    isFallback: true
  };
}

export function getListingVisual(listing, apiUrl = "") {
  const photo = listing?.photos?.find((item) => normalizePhotoUrl(item?.url, apiUrl));
  const src = normalizePhotoUrl(photo?.url, apiUrl);
  if (src) {
    return {
      src,
      category: listing?.category ?? fallbackCategory,
      color: CATEGORY_VISUALS[listing?.category]?.color ?? CATEGORY_VISUALS[fallbackCategory].color,
      credit: photo.credit ?? "",
      href: photo.href ?? "",
      isFallback: false
    };
  }
  const fallback = getCategoryVisual(listing?.category, listing?.id ?? listing?.title);
  return { ...fallback, src: fallback.url };
}
